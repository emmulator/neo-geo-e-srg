;;; user_commands.s — the E-SRG sound driver commands (M7 Task 1, K1).
;;;
;;; The cart's game effects (move, fire, jump, hit, crack, the lock-on pip)
;;; and the initials picker's (tick, type, bell, backspace) as ADPCM-A
;;; samples in the V ROM, each reachable by one command byte:
;;;
;;;   4 fire   (channel 3)     6 hit    (channel 2)     8 pip  (channel 1)
;;;   5 jump   (channel 0)     7 crack  (channel 2)     9 move (channel 0)
;;;   10 tick  (channel 3)     12 bell   (channel 5)
;;;   11 type  (channel 4)     13 back   (channel 4)
;;;
;;; jump and the scuttle share ADPCM-A channel 0, hit and crack share
;;; channel 2, the pip has channel 1 to itself: starting a sample on a
;;; channel stops whatever that channel was playing, as on the Vectrex's AY
;;; (the effect groups sit on the same AY channels). The scuttle joining
;;; channel 0 is the design's call: a jump that starts as a step ends cuts
;;; the scuttle's tail, which is right. The shot has channel 3, shared with
;;; the picker's tick, which never plays in a game: a walk's next step can no
;;; longer chop a shot off mid-sample (a click, heard as distortion). The picker has channels 3, 4 and 5
;;; (type and backspace share 4), so its sounds never cut a game effect and
;;; a tick and a type on the same frame (the pick on the arrival frame)
;;; both play. Command 2 is unused — today's cart
;;; is silent at boot (checked 2026-10-19), so there is no eye-catcher
;;; music. Nullsound's command FIFO acknowledges each command by writing
;;; cmd | 0x80 back to the 68k port; src/sound.c waits for that before
;;; sending the next command, so two sounds in one frame both play.
        .include "helpers.inc"
        .area   CODE

cmd_jmptable::
        ;; common/reserved sound commands
        jp      snd_command_unused                      ; 0
        jp      snd_command_01_prepare_for_rom_switch   ; 1 (BIOS)
        jp      snd_command_unused                      ; 2: no eye-catcher
                                                        ; music (silent boot)
        jp      snd_command_03_reset_driver             ; 3 (BIOS)
        jp      play_fire                               ; 4
        jp      play_jump                               ; 5
        jp      play_hit                                ; 6
        jp      play_crack                              ; 7
        jp      play_pip                                ; 8
        jp      play_move                               ; 9
        jp      play_tick                               ; 10
        jp      play_type                               ; 11
        jp      play_bell                               ; 12
        jp      play_back                               ; 13
        init_unused_cmd_jmptable

;;; each play command: point IX at the sample's 7-byte config and let
;;; nullsound start the sample on that channel (which stops whatever that
;;; channel was playing)
play_fire:
        ld      ix, #adpcm_a_fire
        call    snd_adpcm_a_play
        ret

play_jump:
        ld      ix, #adpcm_a_jump
        call    snd_adpcm_a_play
        ret

play_hit:
        ld      ix, #adpcm_a_hit
        call    snd_adpcm_a_play
        ret

play_crack:
        ld      ix, #adpcm_a_crack
        call    snd_adpcm_a_play
        ret

play_pip:
        ld      ix, #adpcm_a_pip
        call    snd_adpcm_a_play
        ret

play_move:
        ld      ix, #adpcm_a_move
        call    snd_adpcm_a_play
        ret

play_tick:
        ld      ix, #adpcm_a_tick
        call    snd_adpcm_a_play
        ret

play_type:
        ld      ix, #adpcm_a_type
        call    snd_adpcm_a_play
        ret

play_bell:
        ld      ix, #adpcm_a_bell
        call    snd_adpcm_a_play
        ret

play_back:
        ld      ix, #adpcm_a_back
        call    snd_adpcm_a_play
        ret

;;; the samples' offsets in the V ROM, generated by vromtool.py --asm
;;; (build/samples.inc, from sound/samples-map.yaml)
        .include "samples.inc"

adpcm_a_fire:
        .db     FIRE_START_LSB
        .db     FIRE_START_MSB
        .db     FIRE_STOP_LSB
        .db     FIRE_STOP_MSB
        .db     3                       ; ADPCM-A channel 3 (the picker's tick)
        .db     0xdf                    ; left+right outputs, full volume
        .db     8                       ; channel 3 (bit)
adpcm_a_jump:
        .db     JUMP_START_LSB
        .db     JUMP_START_MSB
        .db     JUMP_STOP_LSB
        .db     JUMP_STOP_MSB
        .db     0                       ; ADPCM-A channel 0
        .db     0xdf
        .db     1
adpcm_a_hit:
        .db     HIT_START_LSB
        .db     HIT_START_MSB
        .db     HIT_STOP_LSB
        .db     HIT_STOP_MSB
        .db     2                       ; ADPCM-A channel 2
        .db     0xdf
        .db     4                       ; 1 << 2
adpcm_a_crack:
        .db     CRACK_START_LSB
        .db     CRACK_START_MSB
        .db     CRACK_STOP_LSB
        .db     CRACK_STOP_MSB
        .db     2                       ; ADPCM-A channel 2
        .db     0xdf
        .db     4
adpcm_a_pip:
        .db     PIP_START_LSB
        .db     PIP_START_MSB
        .db     PIP_STOP_LSB
        .db     PIP_STOP_MSB
        .db     1                       ; ADPCM-A channel 1
        .db     0xdf
        .db     2                       ; 1 << 1
adpcm_a_move:
        .db     MOVE_START_LSB
        .db     MOVE_START_MSB
        .db     MOVE_STOP_LSB
        .db     MOVE_STOP_MSB
        .db     0                       ; ADPCM-A channel 0 (with fire/jump)
        .db     0xdf
        .db     1                       ; 1 << 0
adpcm_a_tick:
        .db     TICK_START_LSB
        .db     TICK_START_MSB
        .db     TICK_STOP_LSB
        .db     TICK_STOP_MSB
        .db     3                       ; ADPCM-A channel 3
        .db     0xdf
        .db     8                       ; 1 << 3
adpcm_a_type:
        .db     TYPE_START_LSB
        .db     TYPE_START_MSB
        .db     TYPE_STOP_LSB
        .db     TYPE_STOP_MSB
        .db     4                       ; ADPCM-A channel 4
        .db     0xdf
        .db     16                      ; 1 << 4
adpcm_a_bell:
        .db     BELL_START_LSB
        .db     BELL_START_MSB
        .db     BELL_STOP_LSB
        .db     BELL_STOP_MSB
        .db     5                       ; ADPCM-A channel 5
        .db     0xdf
        .db     32                      ; 1 << 5
adpcm_a_back:
        .db     BACKSPACE_START_LSB
        .db     BACKSPACE_START_MSB
        .db     BACKSPACE_STOP_LSB
        .db     BACKSPACE_STOP_MSB
        .db     4                       ; ADPCM-A channel 4 (with type)
        .db     0xdf
        .db     16                      ; 1 << 4
