;;; user_commands.s — the E-SRG sound driver commands (M7 Task 1).
;;;
;;; The cart's five sound effects (fire, jump, hit, crack, the lock-on pip)
;;; as ADPCM-A samples in the V ROM, each reachable by one command byte:
;;;
;;;   4 fire   (channel 0)     6 hit    (channel 2)     8 pip (channel 1)
;;;   5 jump   (channel 0)     7 crack  (channel 2)
;;;
;;; fire and jump share ADPCM-A channel 0, hit and crack share channel 2,
;;; the pip has channel 1 to itself: starting a sample on a channel stops
;;; whatever that channel was playing, as on the Vectrex's AY (the effect
;;; groups sit on the same AY channels). Command 2 is unused — today's cart
;;; is silent at boot (checked 2026-10-19), so there is no eye-catcher
;;; music. Nullsound's command FIFO acknowledges each command by writing
;;; cmd | 0x80 back to the 68k port; src/sound.c waits for that before
;;; sending the next command, so two sounds in one frame both play.
        .include "helpers.inc"
        .area   CODE

cmd_jmptable::
        ;; common/reserved sound commands
        jp      snd_command_unused                      ; 0
        jp      snd_command_01_prepare_for_rom_switch   ; 1 (BIOS)
        jp      snd_command_unused                      ; 2: no eye-catcher
                                                        ; music (silent boot)
        jp      snd_command_03_reset_driver             ; 3 (BIOS)
        jp      play_fire                               ; 4
        jp      play_jump                               ; 5
        jp      play_hit                                ; 6
        jp      play_crack                              ; 7
        jp      play_pip                                ; 8
        init_unused_cmd_jmptable

;;; each play command: point IX at the sample's 7-byte config and let
;;; nullsound start the sample on that channel (which stops whatever that
;;; channel was playing)
play_fire:
        ld      ix, #adpcm_a_fire
        call    snd_adpcm_a_play
        ret

play_jump:
        ld      ix, #adpcm_a_jump
        call    snd_adpcm_a_play
        ret

play_hit:
        ld      ix, #adpcm_a_hit
        call    snd_adpcm_a_play
        ret

play_crack:
        ld      ix, #adpcm_a_crack
        call    snd_adpcm_a_play
        ret

play_pip:
        ld      ix, #adpcm_a_pip
        call    snd_adpcm_a_play
        ret

;;; the samples' offsets in the V ROM, generated by vromtool.py --asm
;;; (build/samples.inc, from sound/samples-map.yaml)
        .include "samples.inc"

adpcm_a_fire:
        .db     FIRE_START_LSB
        .db     FIRE_START_MSB
        .db     FIRE_STOP_LSB
        .db     FIRE_STOP_MSB
        .db     0                       ; ADPCM-A channel 0
        .db     0xdf                    ; left+right outputs, full volume
        .db     1                       ; channel 0 (bit)
adpcm_a_jump:
        .db     JUMP_START_LSB
        .db     JUMP_START_MSB
        .db     JUMP_STOP_LSB
        .db     JUMP_STOP_MSB
        .db     0                       ; ADPCM-A channel 0
        .db     0xdf
        .db     1
adpcm_a_hit:
        .db     HIT_START_LSB
        .db     HIT_START_MSB
        .db     HIT_STOP_LSB
        .db     HIT_STOP_MSB
        .db     2                       ; ADPCM-A channel 2
        .db     0xdf
        .db     4                       ; 1 << 2
adpcm_a_crack:
        .db     CRACK_START_LSB
        .db     CRACK_START_MSB
        .db     CRACK_STOP_LSB
        .db     CRACK_STOP_MSB
        .db     2                       ; ADPCM-A channel 2
        .db     0xdf
        .db     4
adpcm_a_pip:
        .db     PIP_START_LSB
        .db     PIP_START_MSB
        .db     PIP_STOP_LSB
        .db     PIP_STOP_MSB
        .db     1                       ; ADPCM-A channel 1
        .db     0xdf
        .db     2                       ; 1 << 1
