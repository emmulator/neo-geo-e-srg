#!/usr/bin/env python3
"""render_ship.py SHEET.gif HEADER.h [--preview PNG]

Renders the ship (the Vectrex game's 3-sided pyramid, nose toward the peak)
at each of its 48 latitudes on the dome's front meridian, lit like the dome,
as 32x32 px sprites (2 columns x 2 tiles) into one indexed 16-colour sheet,
and writes the C header with each view's tile numbers and its place in the
dome box. The ship only ever changes latitude: the dome turns under it."""
import argparse
import math
import os
import sys

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geometry as g  # noqa: E402
import render_dome as rd  # noqa: E402

SIZE = 32                                   # sprite: SIZE x SIZE px
COLS = ROWS = SIZE // 16
PAD = 6                                     # px kept above the ship's top
OX = g.DOME_W // 2 - SIZE // 2              # sprite x in the dome box (the ship is centred)
TILE_BASE = rd.TILE_BASE + g.VIEWS * rd.COLS * rd.ROWS   # C ROM: right after the dome

PALETTE = [
    (255, 0, 255),                                            # 0 transparent (key colour)
    (70, 28, 6), (105, 44, 8), (145, 64, 10), (185, 88, 14),  # 1-6 hull, dark to light
    (218, 116, 22), (242, 150, 40),
    (120, 50, 10),                                            # 7 spare
    (150, 70, 20), (190, 100, 30), (220, 135, 45),            # 8-10 glow ramp
    (240, 170, 70), (250, 200, 110), (255, 222, 150),         # 11-13
    (255, 240, 200), (255, 255, 240),                         # 14-15 core
]
HULL = [PALETTE[i] for i in range(1, 7)]
EDGE_GLOW = PALETTE[9]
EDGE_CORE = PALETTE[15]


def placed_views():
    """per latitude: (ship points in sprite px, model points, faces, sprite y in the dome box)."""
    pts, _, faces = g.build_mesh()
    g.make_cells(pts, faces)                # sets g.SHIP_MAX_DEG: the lowest cell centre
    f = g.fit()
    out = []
    for i in range(g.SHIP_STEPS):
        theta = math.radians(g.SHIP_MAX_DEG) * i / (g.SHIP_STEPS - 1)
        sp, sf = g.ship_model(theta)
        px = g.to_px(g.project(sp, 0)[0], f)
        oy = math.floor(px[:, 1].min()) - PAD
        out.append((px - np.array([OX, oy]), sp, sf, oy))
    return out


def render(local, sp, sf):
    pos = g.camera()[0]
    ctr = sp.mean(axis=0)
    img = Image.new("RGBA", (SIZE * rd.SS, SIZE * rd.SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for face in sf:
        P = sp[face]
        n = np.cross(P[1] - P[0], P[2] - P[0])
        fc = P.mean(axis=0)
        if n @ (fc - ctr) < 0:
            n = -n
        if n @ (pos - fc) <= 0:
            continue                        # faces away from the camera
        shade = round(5 * max(0.0, float(n / np.linalg.norm(n) @ g.LIGHT)))
        d.polygon([tuple(local[k] * rd.SS) for k in face], fill=HULL[shade] + (255,))
    segs = [(local[a], local[b]) for a, b in g.ship_visible_edges(sp, sf)]
    for colour, width, alpha in ((EDGE_GLOW, 6, 0.6), (EDGE_CORE, 3, 1.0)):
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        rd.lines(layer, segs, colour, width, alpha)
        img = Image.alpha_composite(img, layer)
    return img.resize((SIZE, SIZE), Image.BOX)


def quantize(img):
    a = np.asarray(img).astype(float)
    pal = np.array(PALETTE[1:], float)
    idx = ((a[..., None, :3] - pal[None, None]) ** 2).sum(-1).argmin(-1) + 1
    idx[a[..., 3] < 128] = 0
    return idx.astype(np.uint8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sheet")
    ap.add_argument("header")
    ap.add_argument("--preview")
    args = ap.parse_args()

    views = placed_views()
    sheet = np.zeros((SIZE * g.SHIP_STEPS, SIZE), np.uint8)
    for i, (local, sp, sf, _) in enumerate(views):
        img = render(local, sp, sf)
        # the ship sits on the mirror plane: average with its mirror image so
        # rasterisation ties can't make it lopsided (as render_dome does)
        img = Image.blend(img, img.transpose(Image.FLIP_LEFT_RIGHT), 0.5)
        sheet[i * SIZE:(i + 1) * SIZE] = quantize(img)

    im = Image.fromarray(sheet, "P")
    flat = [c for rgb in PALETTE for c in rgb]
    im.putpalette(flat)
    im.save(args.sheet)
    if args.preview:
        strip = np.hstack([sheet[i * SIZE:(i + 1) * SIZE] for i in range(0, g.SHIP_STEPS, 6)])
        pv = Image.fromarray(strip, "P")
        pv.putpalette(flat)
        pv.convert("RGB").resize((strip.shape[1] * 4, SIZE * 4), Image.NEAREST).save(args.preview)

    with open(args.header, "w") as h:
        h.write("/* generated by tools/render_ship.py: do not edit */\n"
                f"#define SHIP_VIEWS {g.SHIP_STEPS}\n#define SHIP_COLS {COLS}\n"
                f"#define SHIP_ROWS {ROWS}\n#define SHIP_TILE_BASE {TILE_BASE}\n"
                f"#define SHIP_OX {OX}      /* sprite x in the dome box */\n"
                "/* tile number of latitude view v, column c, row r (top to bottom) */\n"
                "static const u16 ship_tile[SHIP_VIEWS][SHIP_COLS][SHIP_ROWS] = {\n")
        for v in range(g.SHIP_STEPS):
            cols = ["{" + ",".join(str(TILE_BASE + (v * ROWS + r) * COLS + c) for r in range(ROWS)) + "}"
                    for c in range(COLS)]
            h.write("  {" + ",".join(cols) + "},\n")
        h.write("};\n/* sprite y in the dome box, per latitude view */\n"
                "static const s16 ship_oy[SHIP_VIEWS] = {\n  "
                + ", ".join(str(oy) for *_, oy in views) + "\n};\n")


if __name__ == "__main__":
    main()
