#!/usr/bin/env python3
"""gen_radar.py HEADER.h: the radar's per-ring and per-step tables as a C
header (build/radar_tables.h), from the Vectrex's radar geometry (radar.s's
per-ring factors from tools/gen_dome.py radar_k, with the task's Neo Geo
px constants).

The radar's own constants live in src/radar.h (the user's tuning block);
THIS script reads them from there, so the tables always follow. The C
per-frame code (src/radar.c radar_blip) then keeps to 16-bit maths: for a
missile at ring `ring`, on-screen azimuth j (rotation steps), with
r6 = R/6 in 256ths (0..256):

    sx = CX + round(r6 * radar_rx[ring] * radar_sin[j] / 65536)
    sy = CY + round(r6 * radar_ry[ring] * radar_cos[j] / 65536)
    h  = round(r6 * radar_hv[ring] / 256)

with

    radar_rx[ring] = round(sin(theta) * RADAR_RX * 256)
    radar_ry[ring] = round(sin(theta) * RADAR_RY * 256)      (RY = 8.4)
    radar_hv[ring] = round(cos(theta)^RADAR_H_POW * RADAR_H * 256)
    radar_sin[j]   = round(sin(2*pi*j/240) * 256)
    radar_cos[j]   = round(cos(2*pi*j/240) * 256)

`round` is round-half-up (floor(x + 0.5)): the C's fixed point rounds the
same way. The ring polar angles theta come from geometry.make_cells via
gen_missiles.mis_rings, the same source as the missile tables (the plan's
"its ring's polar angle (from gen_missiles.py's ring table)"); RADAR_RINGS
must equal MIS_RINGS, asserted against the built missiles_tables.h."""
import math
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geometry as g  # noqa: E402
from gen_missiles import mis_rings  # noqa: E402

STEPS = g.STEPS


def ring_thetas():
    """the rings' polar angles, as gen_missiles.tables() computes them (the
    task's "ring table"): the 12 distinct rounded thetas."""
    pts, _, faces = g.build_mesh()
    cells = g.make_cells(pts, faces)
    th, _ = mis_rings(cells)
    return [round(float(t), 6) for t in th]


def rint(x):
    """round-half-up to the nearest integer (the C's fixed point rounds so)."""
    return int(math.floor(x + 0.5))


def radar_h_defs():
    """read the user's constants from src/radar.h (the one tuning block).
    RADAR_CY was an expression in the dome's header (DOME_Y + 112); since
    Dome-scenery Task 2 it is a literal, and Task 8 moved it to 206 (onto
    the console's left wing). A DOME_Y expression is still resolved here,
    so the expression path keeps working. Fail loudly if a constant
    drifts."""
    hdr = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "..", "src", "radar.h")
    txt = open(hdr).read()
    out = {}
    for name in ("RADAR_CX", "RADAR_CY", "RADAR_RX", "RADAR_RY", "RADAR_H",
                 "RADAR_H_POW"):
        m = re.search(r"#define\s+%s\s+(.+)$" % name, txt, re.M)
        assert m, f"{name} missing from src/radar.h"
        value = m.group(1).split("/*")[0].strip()
        if "DOME_Y" in value:
            dome = open(os.path.join(os.path.dirname(hdr), "dome.h")).read()
            dy = int(re.search(r"#define\s+DOME_Y\s+(\d+)", dome).group(1))
            value = value.replace("DOME_Y", str(dy))
        out[name] = eval(value)
    return out


def main():
    d = radar_h_defs()
    rx, ry10, h, hpow = d["RADAR_RX"], d["RADAR_RY"], d["RADAR_H"], d["RADAR_H_POW"]
    th = ring_thetas()
    # the C header's ring count must be the missile tables' MIS_RINGS
    built = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "..", "build", "missiles_tables.h")
    mis_rings_n = int(re.search(r"#define MIS_RINGS\s+(\d+)",
                                open(built).read()).group(1))
    assert len(th) == mis_rings_n, (len(th), mis_rings_n)

    ry = ry10 / 10.0                    # 84 -> 8.4 px (the header stores tenths)
    rx_tab = [rint(math.sin(t) * rx * 256) for t in th]
    ry_tab = [rint(math.sin(t) * ry * 256) for t in th]
    hv_tab = [rint(math.cos(t) ** hpow * h * 256) for t in th]
    assert all(0 <= v <= 65535 for v in rx_tab + ry_tab + hv_tab)
    sin_tab = [rint(math.sin(2 * math.pi * j / STEPS) * 256) for j in range(STEPS)]
    cos_tab = [rint(math.cos(2 * math.pi * j / STEPS) * 256) for j in range(STEPS)]

    def arr(name, ctype, vals, per=16):
        rows = [", ".join(map(str, vals[i:i + per])) for i in range(0, len(vals), per)]
        return f"static const {ctype} {name} = {{\n  " + ",\n  ".join(rows) + "\n};\n"

    with open(sys.argv[1], "w") as hf:
        w = hf.write
        w("/* generated by tools/gen_radar.py: do not edit */\n"
          "#ifndef RADAR_TABLES_H\n#define RADAR_TABLES_H\n")
        w(f"#define RADAR_RINGS {len(th)}      /* the missile table's MIS_RINGS, "
          "asserted at gen time */\n")
        w(f"/* the radar's per-ring factors, from src/radar.h's constants "
          f"(RX {rx}, RY {ry:g}, H {h}, POW {hpow}) and the rings' polar angles\n"
          "   (0..~63.5 deg): spot x per R/6 (px, Q8), spot y per R/6 (px, Q8), "
          "stick height per R/6 (px, Q8) */\n")
        w(arr("radar_rx[RADAR_RINGS]", "u16", rx_tab))
        w(arr("radar_ry[RADAR_RINGS]", "u16", ry_tab))
        w(arr("radar_hv[RADAR_RINGS]", "u16", hv_tab))
        w(f"/* sin and cos of the on-screen azimuth j (rotation steps, 240 per "
          "turn), Q8 (signed) */\n")
        w(arr("radar_sin[240]", "s16", sin_tab))
        w(arr("radar_cos[240]", "s16", cos_tab))
        w("#endif\n")
    print(f"radar tables: {len(th)} rings, {STEPS} steps "
          f"(rx max {max(rx_tab)}, ry max {max(ry_tab)}, hv max {max(hv_tab)})")


if __name__ == "__main__":
    main()
