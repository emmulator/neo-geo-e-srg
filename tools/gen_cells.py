#!/usr/bin/env python3
"""gen_cells.py HEADER.h: the ship's movement tables as a C header: which
dome rotation brings each cell to the front, each cell's ship latitude, its
neighbours with their directions on screen, and the peak's "down" cell per
view. They come from geometry.make_cells (copied from the Vectrex game), so
the same stick input moves the ship along the same cells."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geometry as g  # noqa: E402


def tables():
    pts, _, faces = g.build_mesh()
    return g.make_cells(pts, faces)


def start_cell(c):
    """the Vectrex game's start cell (gen_dome.py): latitude nearest 30,
    then nearest the front."""
    return min(range(1, c["n"]), key=lambda i: (abs(c["lat"][i] - 30),
                                                min(c["step"][i], g.STEPS - c["step"][i])))


def c_array(name, ctype, values, per_line=16):
    rows = [", ".join(map(str, values[i:i + per_line])) for i in range(0, len(values), per_line)]
    return f"static const {ctype} {name} = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def c_rows(name, ctype, rows):
    body = ",\n  ".join("{" + ", ".join(map(str, r)) + "}" for r in rows)
    return f"static const {ctype} {name} = {{\n  " + body + "\n};\n"


def main():
    c = tables()
    adj = [[x for pair in row for x in pair] for row in c["adj"]]
    with open(sys.argv[1], "w") as h:
        h.write("/* generated by tools/gen_cells.py: do not edit */\n"
                "#ifndef CELLS_H\n#define CELLS_H\n"
                f"#define NCELLS     {c['n']}\n"
                f"#define CELL_START {start_cell(c)}\n"
                f"#define CELL_VIEWS {g.VIEWS}     /* peak_down entries: step % CELL_VIEWS */\n"
                f"#define SHIP_LATS  {g.SHIP_STEPS}     /* ship latitudes: 0 = peak */\n"
                "/* rotation step (0..239) that brings the cell to the front */\n"
                + c_array("cell_step[NCELLS]", "u8", c["step"])
                + "/* ship latitude of the cell's centre */\n"
                + c_array("cell_lat[NCELLS]", "u8", c["lat"])
                + "/* up to 6 (direction on screen in 1/256 turn, neighbour) pairs,\n"
                  "   neighbour 255 = none, in the cell's resting view */\n"
                + c_rows("cell_adj[NCELLS][12]", "u8", adj)
                + "/* at the peak, \"down\" goes to the ring cell nearest the front */\n"
                + c_array("peak_down[CELL_VIEWS]", "u8", c["peak_down"])
                + "#endif\n")


if __name__ == "__main__":
    main()
